// English and Finnish (Ton, 14 Oct 2026). The English text is the key and FI holds
// its Finnish. A text missing from FI shows in English. {name} marks a value.
// Page text in index.html carries its English in data-i18n attributes, so
// translatePage() can switch it back and forth.
let lang = 'en';
export const getLang = () => lang;
export const locale = () => (lang === 'fi' ? 'fi-FI' : 'en-GB');
export const num = (n, options) => n.toLocaleString(locale(), options);

export function setLang(next) {
  lang = next === 'fi' ? 'fi' : 'en';
  document.documentElement.lang = lang;
}

export function t(text, vars) {
  const s = lang === 'fi' ? (FI[text] ?? text) : text;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => vars[k] ?? m) : s;
}
// A count with its word: tn(3, '{n} area', '{n} areas') -> "3 areas" / "3 aluetta".
export const tn = (n, one, many, vars = {}) => t(n === 1 ? one : many, {...vars, n: num(n)});

// data-i18n: text, data-i18n-html: markup (our own strings only),
// data-i18n-title: tooltip, data-i18n-label: aria-label.
export function translatePage(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-html]')) node.innerHTML = t(node.dataset.i18nHtml);
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll('[data-i18n-label]'))
    node.setAttribute('aria-label', t(node.dataset.i18nLabel));
}

